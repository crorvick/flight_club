// Recurring maintenance: an annual, 100-hour, ELT check, VOR check, AD
// and so on.  Due by calendar time (months, to the end of the month or to
// the day, or days), by hours on the aircraft's logbook meter, or
// whichever comes first; the next due date and reading are computed from
// the last completion (lib/maintenance.ts), never stored.
export const maintenanceItem = pgTable(
  "maintenance_item",
  {
    id: id(),
    aircraftId: uuid("aircraft_id")
      .notNull()
      .references(() => aircraft.id),
    name: text("name").notNull(),
    // What logging a completion asks for (lib/maintenance-kinds.ts).
    kind: maintenanceKind("kind").default("general").notNull(),
    // Recurring items have intervals, counted from the last completion;
    // the others say when they're due (dueOn, dueReading).
    schedule: maintenanceSchedule("schedule").default("recurring").notNull(),
    intervalMonths: integer("interval_months"),
    intervalDays: integer("interval_days"),
    // Months run to the end of the month (annuals, ELTs) unless this is
    // false; days are always exact (a 30-day VOR check).
    dueEndOfMonth: boolean("due_end_of_month").default(true).notNull(),
    // Counted on the aircraft's logbook meter.
    intervalHours: hours("interval_hours"),
    lastCompletedOn: date("last_completed_on"),
    lastCompletedReading: hours("last_completed_reading"),
    // When one done once is due, by either or both, or when one that
    // expires does; the reading is on the logbook meter.
    dueOn: date("due_on"),
    dueReading: hours("due_reading"),
    // When it was done for good: one done once, or a recurring AD or SB's
    // terminating action.  It's never due again.
    closedOn: date("closed_on"),
    // An AD or SB's number, what it covers, and if it was found not to
    // apply to this aircraft (outside the serial range, say), why.
    reference: text("reference"),
    appliesTo: directiveScope("applies_to"),
    notApplicable: text("not_applicable"),
    // Chosen per item: an overdue annual grounds the aircraft, an overdue
    // VOR check rules out only IFR, an overdue oil change might only warn.
    grounding: grounding("grounding").default("none").notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    index("maintenance_item_aircraft_idx").on(table.aircraftId),
    check(
      "maintenance_item_has_interval",
      sql`${table.schedule} <> 'recurring'
        or ${table.notApplicable} is not null
        or ${table.intervalMonths} is not null
        or ${table.intervalDays} is not null
        or ${table.intervalHours} is not null`,
    ),
    check(
      "maintenance_item_intervals_recur",
      sql`${table.schedule} = 'recurring'
        or (${table.intervalMonths} is null
          and ${table.intervalDays} is null
          and ${table.intervalHours} is null)`,
    ),
    check(
      "maintenance_item_once_due",
      sql`${table.schedule} <> 'once'
        or ${table.notApplicable} is not null
        or ${table.dueOn} is not null
        or ${table.dueReading} is not null`,
    ),
    check(
      "maintenance_item_expires_due",
      sql`${table.schedule} <> 'expires'
        or ${table.notApplicable} is not null
        or ${table.dueOn} is not null`,
    ),
    check(
      "maintenance_item_due_reading_once",
      sql`${table.dueReading} is null or ${table.schedule} = 'once'`,
    ),
    // A calendar interval is months or days, not both.
    check(
      "maintenance_item_one_calendar_interval",
      sql`${table.intervalMonths} is null or ${table.intervalDays} is null`,
    ),
    check(
      "maintenance_item_months_positive",
      sql`${table.intervalMonths} is null or ${table.intervalMonths} > 0`,
    ),
    check(
      "maintenance_item_days_positive",
      sql`${table.intervalDays} is null or ${table.intervalDays} > 0`,
    ),
    // An hours interval needs a reading to count from; a calendar
    // interval needs a date.
    check(
      "maintenance_item_hours_complete",
      sql`${table.intervalHours} is null
        or (${table.intervalHours} > 0
          and ${table.lastCompletedReading} is not null)`,
    ),
    check(
      "maintenance_item_calendar_complete",
      sql`(${table.intervalMonths} is null and ${table.intervalDays} is null)
        or ${table.lastCompletedOn} is not null`,
    ),
  ],
);

// Each time an item was done, so its history survives the item being
// reset by the next completion.
export const maintenanceCompletion = pgTable(
  "maintenance_completion",
  {
    id: id(),
    itemId: uuid("item_id")
      .notNull()
      .references(() => maintenanceItem.id, { onDelete: "cascade" }),
    completedOn: date("completed_on").notNull(),
    reading: hours("reading"),
    note: text("note"),
    // What the item's kind records beyond the date and reading, such as a
    // VOR check's bearing errors.  Null for general items.
    details: jsonb("details").$type<CompletionDetails>(),
    // For an item that expires, the new expiration date.
    expiresOn: date("expires_on"),
    recordedById: uuid("recorded_by_id").references(() => member.id, {
      onDelete: "set null",
    }),
    createdAt: createdAt(),
  },
  (table) => [
    index("maintenance_completion_item_idx").on(
      table.itemId,
      table.completedOn,
    ),
  ],
);

// Who changed what, and when, with the record before and after.  Written
// for officer edits to locked flights and for squawk resolutions; actor is
// null for changes made by scripts.
export const auditLog = pgTable(
  "audit_log",
  {
    id: id(),
    actorId: uuid("actor_id").references(() => member.id, {
      onDelete: "set null",
    }),
    // What happened, e.g. "flight.update" or "squawk.resolve".
    action: text("action").notNull(),
    entityType: text("entity_type").notNull(),
    entityId: uuid("entity_id").notNull(),
    before: jsonb("before"),
    after: jsonb("after"),
    createdAt: createdAt(),
  },
  (table) => [
    index("audit_log_entity_idx").on(
      table.entityType,
      table.entityId,
      table.createdAt,
    ),
  ],
);

